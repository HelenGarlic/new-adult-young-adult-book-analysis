VOWELS = "aeiouy"

def count_syllables_word(word: str) -> int:
    word = word.lower()
    word = re.sub(r'[^a-z]', '', word)
    if not word:
        return 0

    count = 0
    if word[0] in VOWELS:
        count += 1
    for i in range(1, len(word)):
        if word[i] in VOWELS and word[i-1] not in VOWELS:
            count += 1
    if word.endswith("e"):
        count -= 1
    if word.endswith("le") and len(word) > 2 and word[-3] not in VOWELS:
        count += 1
    if count <= 0:
        count = 1
    return count


def count_syllables_text(text: str) -> int:
    if pd.isna(text):
        return 0
    words = re.findall(r"[A-Za-z']+", str(text))
    return sum(count_syllables_word(w) for w in words)

