"""## Контекстный анализ лексем *love* и *любовь/любить* в двуязычном корпусе романтической прозы"""

import spacy
import pymorphy3
from collections import Counter, defaultdict
import pandas as pd
import matplotlib.pyplot as plt
import matplotlib
from matplotlib.gridspec import GridSpec
import re

matplotlib.rcParams['font.family'] = 'DejaVu Sans'

nlp_en = spacy.load('en_core_web_sm')
morph = pymorphy3.MorphAnalyzer()

WINDOW = 3  # окно ±3 слова

def get_love_contexts_en(texts: list, window: int = WINDOW):
    """
    Извлекает контекстные окна вокруг love-NOUN и love-VERB из EN текстов.
    texts — список строк (тексты книг)
    Возвращает два списка соседних лемм: для noun и для verb.
    """
    noun_context = []
    verb_context = []

    EN_STOP = {'not', 'i', 'd', 're', 've', 'm', 's',
                'the', 'a', 'an', 'it', 'be', 'do',
                'that', 'this', 'so', 'just', 'get'
                }

    for text in texts:
        doc = nlp_en(str(text))
        tokens = list(doc)
        for i, token in enumerate(tokens):
            if token.lemma_.lower() != 'love':
                continue
            # Соседи в окне
            left  = tokens[max(0, i - window): i]
            right = tokens[i + 1: i + 1 + window]
            neighbors = [t.lemma_.lower() for t in left + right
                         if not t.is_punct and not t.is_space
                         and t.lemma_.lower() not in EN_STOP
                         and len(t.lemma_) > 1
                         and t.lemma_.lower() not in ('love',)]

            if token.pos_ == 'NOUN':
                noun_context.extend(neighbors)
            elif token.pos_ == 'VERB':
                verb_context.extend(neighbors)

    return noun_context, verb_context


def get_love_contexts_ru(texts: list, window: int = WINDOW):
    """
    Извлекает контекстные окна вокруг любовь (NOUN) и любить (VERB) из RU текстов.
    Использует pymorphy3 для лемматизации.
    """
    noun_context = []
    verb_context = []

    RU_STOP = {'и', 'в', 'на', 'с', 'по', 'к', 'за', 'из', 'не',
                 'то', 'а', 'но', 'же', 'бы', 'как', 'что', 'это',
                 'он', 'она', 'они', 'мы', 'я', 'ты', 'вы', 'его',
                 'ее', 'её', 'их', 'мне', 'меня', 'себя', 'себе',
                 'который', 'кто', 'мой', 'твой', 'свой', 'тот',
                'такой', 'весь', 'быть'}

    for text in texts:
        # Разбиваем на токены (слова)
        raw_tokens = re.findall(r'[а-яёА-ЯЁa-zA-Z]+', str(text))
        # Лемматизируем все токены
        lemmas = []
        pos_tags = []
        for w in raw_tokens:
            parsed = morph.parse(w.lower())[0]
            lemmas.append(parsed.normal_form)
            pos_tags.append(parsed.tag.POS)

        for i, (lemma, pos) in enumerate(zip(lemmas, pos_tags)):
            target_lemma = None
            target_type  = None

            if lemma == 'любовь':
                target_lemma = 'любовь'
                target_type  = 'noun'
            elif lemma == 'любить':
                target_lemma = 'любить'
                target_type  = 'verb'

            if target_lemma is None:
                continue

            left  = lemmas[max(0, i - window): i]
            right = lemmas[i + 1: i + 1 + window]
            neighbors = [l for l in left + right
                         if l not in RU_STOP and len(l) > 2
                         and l not in ('любовь', 'любить')]

            if target_type == 'noun':
                noun_context.extend(neighbors)
            else:
                verb_context.extend(neighbors)

    return noun_context, verb_context

en_texts = [en_analyze_df[en_analyze_df['id'] == i]['text_clean'].values[0] for i in en_analyze_df['id'].unique()]
