VOWELS_RU = re.compile(r'[аеёиоуыьъэюяАЕЁИОУЫЬЪЭЮЯ]')
SENT_SPLIT_RU = re.compile(r'[.!?]+')
WORD_RE = re.compile(r'\b\w+\b')

def count_syllables_ru(word: str) -> int:
    return len(VOWELS_RU.findall(word))

def avg_syllables_per_word_ru(text: str) -> float:
    words = WORD_RE.findall(text)
    if not words:
        return 0.0
    return sum(count_syllables_ru(w) for w in words) / len(words)

def flesh_ru(text: str) -> float:
    """Адаптированный индекс Флеша для русского."""
    sents = [s.strip() for s in SENT_SPLIT_RU.split(text) if s.strip()]
    words = WORD_RE.findall(text)
    if not sents or not words:
        return 0.0
    asl = len(words) / len(sents)          # средняя длина предложения
    asw = avg_syllables_per_word_ru(text)  # среднее кол-во слогов
    return 206.835 - 1.3 * asl - 60.1 * asw

def smog_ru(text: str) -> int:
    """SMOG grade для русского (приближение)."""
    sents = [s.strip() for s in SENT_SPLIT_RU.split(text) if s.strip()]
    words = WORD_RE.findall(text)
    if len(sents) < 3:
        return 0
    polysyl = sum(1 for w in words if count_syllables_ru(w) >= 3)
    return int(3 + np.sqrt(polysyl * (30 / len(sents))))

