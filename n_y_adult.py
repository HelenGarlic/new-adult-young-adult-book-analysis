"""### TTR — Type-Token Ratio"""

def compute_ttr(text: str) -> float:
    words = re.findall(r'\b\w+\b', str(text).lower())
    if not words:
        return 0.0
    return len(set(words)) / len(words)

# Вариант MATTR (скользящее окно, устойчивее к длине текста)
def compute_mattr(text: str, window: int = 500) -> float:
    words = re.findall(r'\b\w+\b', str(text).lower())
    if len(words) < window:
        return compute_ttr(text)
    ttrs = [
        len(set(words[i:i+window])) / window
        for i in range(0, len(words) - window + 1, window)
    ]
    return float(np.mean(ttrs))

