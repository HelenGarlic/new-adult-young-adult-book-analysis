def clean_for_readability(text: str) -> str:
    """
    Очищает текст от технической разметки, заголовков глав/частей,
    лишних переносов и пробелов для корректного анализа читаемости.
    """
    text = str(text)

    # 1. Убираем заголовки глав и частей (EN + RU, регистронезависимо)
    # chapter_patterns = [
    #     r'(^|\n)\s*part\s+[a-z0-9ivx]+[^\n]*',
    #     r'(^|\n)\s*chapter\s+[a-z0-9ivx]+[^\n]*',
    #     r'(^|\n)\s*глава\s+[а-яё0-9ivx]+[^\n]*',
    #     r'(^|\n)\s*часть\s+[а-яё0-9ivx]+[^\n]*',
    # ]

    chapter_patterns = [
        r'\b(part|chapter)\s*[a-z0-9ivxlcdm]*\.?',
        r'\b(prologue|epilogue)\.?',
        r'\b(глава|часть|книга|раздел)\s*[а-яёa-z0-9]*\.?',
        r'\b(эпилог|пролог)\.?',
    ]
    for pat in chapter_patterns:
        text = re.sub(pat, ' ', text, flags=re.IGNORECASE)

    # 2. Убираем HTML/XML теги
    text = re.sub(r'<[^>]+>', ' ', text)

    # 3. Убираем URL
    text = re.sub(r'https?://\S+', ' ', text)

    # 4. Табуляции → пробел
    text = re.sub(r'\t', ' ', text)

    # 5. Переносы строк: одиночный \n → пробел (продолжение предложения),
    #    двойной \n\n → точка + пробел (граница абзаца, важно для читаемости)
    text = re.sub(r'\n{2,}', '. ', text)
    text = re.sub(r'\n', ' ', text)

    # 6. Специальные пробельные символы Unicode (\xa0, \u200b и др.) → пробел
    text = re.sub(r'[\xa0\u200b\u200c\u200d\ufeff]', ' ', text)

    # 7. Множественные пробелы → один
    text = re.sub(r' {2,}', ' ', text)

    return text.strip()

