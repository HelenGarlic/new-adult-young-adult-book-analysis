def plot_pos_pie(pos_dict: dict, title: str, label_map: dict = None,
                threshold: float = 0.03, pct_threshold: float = 0.05):
    """
    pct_threshold — минимальная доля для отображения % внутри сектора.
                    Для маленьких секторов процент скрывается.
    """
    if label_map is None:
        label_map = {}

    total = sum(pos_dict.values())
    if total == 0:
        print(f"[{title}] Пустой словарь, пропускаем.")
        return

    renamed = {}
    other_sum = 0
    other_details = {}

    for pos, count in pos_dict.items():
        name = label_map.get(pos, pos)
        share = count / total
        if share < threshold:
            other_sum += count
            other_details[name] = round(share * 100, 1)
        else:
            renamed[name] = renamed.get(name, 0) + count

    if other_sum > 0:
        renamed['Другое'] = other_sum

    if not renamed:
        print(f"[{title}] Все категории < {threshold*100}%, снизь threshold.")
        return

    sorted_pos = dict(sorted(renamed.items(), key=lambda x: x[1], reverse=True))
    values = list(sorted_pos.values())
    labels = list(sorted_pos.keys())
    colors = plt.cm.Paired(np.linspace(0, 1, len(sorted_pos)))

    fig, ax = plt.subplots(figsize=(10, 7))

    # Показываем % только для секторов выше pct_threshold
    def autopct_fn(pct):
        return f'{pct:.1f}%' if pct / 100 >= pct_threshold else ''

