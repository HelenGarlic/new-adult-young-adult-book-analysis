def preprocessing(line,
                  lang='en',
                  remove_punctuation=True,
                  remove_stopwords=True,
                  normalisation=True):
    # нижний регистр
    line = line.lower()

    # удаляем разметку глав
    patterns = [
        r'(^|\n)\s*part\s+[a-z0-9ivx]+',
        r'(^|\n)\s*chapter\s+[a-z0-9ivx]+',
        r'(^|\n)\s*глава\s+[а-яё0-9ivx]+',
        r'(^|\n)\s*часть\s+[а-яё0-9ivx]+',
    ]
    for pat in patterns:
        line = re.sub(pat, r'\1 ', line)

    # переносы → пробелы
    line = re.sub('\n\t', ' ', line)

    # оставляем только рус/англ буквы, цифры и пунктуацию
    line = re.sub(r'[^а-яёa-z0-9\s{}]'.format(string.punctuation), '', line)

    # убрать пунктуацию
    if remove_punctuation:
        line = re.sub(r"[{}]".format(string.punctuation), " ", line)

    # токенизация по пробелам
    words = [x for x in re.split(r'\s+', line) if x]

    # удаление стоп-слов
    if remove_stopwords:
        stop_words = eng_stopwords if lang == 'en' else ru_stopwords
        words = [x for x in words if x not in stop_words]

    # лемматизация
    if normalisation:
        lemmas = []
        if lang == 'ru':
            for x in words:
                p = morph.parse(x)[0]
                lemmas.append(p.normal_form)
        elif lang == 'en':
            for x in words:
                pos = nltk_pos_tag(x)
                lemmas.append(lemmatizer.lemmatize(x, pos))
        else:
            lemmas = words
    else:
        lemmas = words

    return ' '.join(lemmas)

