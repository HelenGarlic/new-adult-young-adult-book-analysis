import os
import ebooklib
from ebooklib import epub
from bs4 import BeautifulSoup
from pathlib import Path

BLOCKLIST = ['[document]', 'noscript', 'header', 'html', 'meta', 'head', 'input', 'script']

def chapter_to_text(chapter_content: bytes) -> str:
    soup = BeautifulSoup(chapter_content, 'html.parser')
    output, prev = [], ''
    for tag in soup.find_all(string=True):
        if tag.parent.name not in BLOCKLIST and not tag.isspace():
            if not (str(prev).endswith(' ') or str(tag).startswith(' ')):
                output.append('\n\n')
            output.append(str(tag))
            prev = tag
    return ''.join(output)

def convert(epub_path: str, output_dir: str) -> str:
    os.makedirs(output_dir, exist_ok=True)
    book = epub.read_epub(epub_path)
    txt_path = os.path.join(output_dir, Path(epub_path).stem + '.txt')

    with open(txt_path, 'w', encoding='utf-8') as f:
        for item in book.get_items():
            if item.get_type() == ebooklib.ITEM_DOCUMENT:
                f.write(chapter_to_text(item.get_content()) + '\n')

    print(f"✅ Готово: {txt_path}")
    return txt_path

for f in epub_files:
    convert(f, output_dir)

